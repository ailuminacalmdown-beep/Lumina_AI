import os
import sqlite3


SQLITE_DB = os.path.join(
    os.path.dirname(__file__),
    "lumina.db"
)

DATABASE_URL = os.environ.get("DATABASE_URL")


def get_sqlite_connection():
    conn = sqlite3.connect(SQLITE_DB)
    conn.row_factory = sqlite3.Row
    return conn


def get_postgres_connection():
    import psycopg
    from psycopg.rows import dict_row

    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL est absente. "
            "La migration n'a pas été exécutée."
        )

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )


def create_postgres_schema(conn):
    with conn.cursor() as cur:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                display_name TEXT,
                created_at DOUBLE PRECISION NOT NULL
            );

            CREATE TABLE IF NOT EXISTS sessions (
                token TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL,
                created_at DOUBLE PRECISION NOT NULL,
                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            );

            CREATE TABLE IF NOT EXISTS user_knowledge (
                user_id BIGINT PRIMARY KEY,
                connaissances TEXT NOT NULL DEFAULT '{}',
                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            );

            CREATE TABLE IF NOT EXISTS conv_memories (
                user_id BIGINT NOT NULL,
                conv_id TEXT NOT NULL,
                historique TEXT NOT NULL DEFAULT '[]',
                updated_at DOUBLE PRECISION NOT NULL,
                PRIMARY KEY (user_id, conv_id),
                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            );

            CREATE TABLE IF NOT EXISTS memories (
                user_id BIGINT PRIMARY KEY,
                historique TEXT NOT NULL DEFAULT '[]',
                connaissances TEXT NOT NULL DEFAULT '{}',
                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            );
        """)

    conn.commit()

def migrate_users(sqlite_conn, postgres_conn):
    rows = sqlite_conn.execute("""
        SELECT id, email, password_hash, display_name, created_at
        FROM users
        ORDER BY id
    """).fetchall()

    with postgres_conn.cursor() as cur:
        for row in rows:
            cur.execute("""
                INSERT INTO users
                (id, email, password_hash, display_name, created_at)
                VALUES (%s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
            """, (
                row["id"],
                row["email"],
                row["password_hash"],
                row["display_name"],
                row["created_at"]
            ))

    print(f"Users migrés : {len(rows)}")


def migrate_user_knowledge(sqlite_conn, postgres_conn):
    rows = sqlite_conn.execute("""
        SELECT user_id, connaissances
        FROM user_knowledge
        ORDER BY user_id
    """).fetchall()

    with postgres_conn.cursor() as cur:
        for row in rows:
            cur.execute("""
                INSERT INTO user_knowledge
                (user_id, connaissances)
                VALUES (%s, %s)
                ON CONFLICT (user_id) DO NOTHING
            """, (
                row["user_id"],
                row["connaissances"]
            ))

    print(f"Connaissances migrées : {len(rows)}")


def migrate_conv_memories(sqlite_conn, postgres_conn):
    rows = sqlite_conn.execute("""
        SELECT user_id, conv_id, historique, updated_at
        FROM conv_memories
        ORDER BY user_id, conv_id
    """).fetchall()

    with postgres_conn.cursor() as cur:
        for row in rows:
            cur.execute("""
                INSERT INTO conv_memories
                (user_id, conv_id, historique, updated_at)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (user_id, conv_id) DO NOTHING
            """, (
                row["user_id"],
                row["conv_id"],
                row["historique"],
                row["updated_at"]
            ))

    print(f"Conversations migrées : {len(rows)}")


def migrate_memories(sqlite_conn, postgres_conn):
    rows = sqlite_conn.execute("""
        SELECT user_id, historique, connaissances
        FROM memories
        ORDER BY user_id
    """).fetchall()

    with postgres_conn.cursor() as cur:
        for row in rows:
            cur.execute("""
                INSERT INTO memories
                (user_id, historique, connaissances)
                VALUES (%s, %s, %s)
                ON CONFLICT (user_id) DO NOTHING
            """, (
                row["user_id"],
                row["historique"],
                row["connaissances"]
            ))

    print(f"Mémoires legacy migrées : {len(rows)}")

def migrate_sessions(sqlite_conn, postgres_conn):
    rows = sqlite_conn.execute("""
        SELECT token, user_id, created_at
        FROM sessions
        ORDER BY created_at
    """).fetchall()

    with postgres_conn.cursor() as cur:
        for row in rows:
            cur.execute("""
                INSERT INTO sessions
                (token, user_id, created_at)
                VALUES (%s, %s, %s)
                ON CONFLICT (token) DO NOTHING
            """, (
                row["token"],
                row["user_id"],
                row["created_at"]
            ))

    print(f"Sessions migrées : {len(rows)}")


def main():
    sqlite_conn = get_sqlite_connection()
    postgres_conn = get_postgres_connection()

    try:
        create_postgres_schema(postgres_conn)

        migrate_users(
            sqlite_conn,
            postgres_conn
        )

        with postgres_conn.cursor() as cur:
            cur.execute("""
                SELECT setval(
                    pg_get_serial_sequence('users', 'id'),
                    COALESCE((SELECT MAX(id) FROM users), 1),
                    true
                )
            """)

        migrate_user_knowledge(
            sqlite_conn,
            postgres_conn
        )

        migrate_conv_memories(
            sqlite_conn,
            postgres_conn
        )

        migrate_memories(
            sqlite_conn,
            postgres_conn
        )

        migrate_sessions(
            sqlite_conn,
            postgres_conn
        )

        postgres_conn.commit()

        print("Migration terminée avec succès.")

    except Exception:
        postgres_conn.rollback()
        raise

    finally:
        sqlite_conn.close()
        postgres_conn.close()


if __name__ == "__main__":
    main()
